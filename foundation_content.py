def validate_content():
    for c in COURSES:
        for s in c['steps']:
            b=chess.Board(s['fen'])
            assert b.is_valid(),(c['id'],s['title'],b.status())
            if s['kind']=='move':
                for u in s['line']:
                    m=chess.Move.from_uci(u)
                    assert m in b.legal_moves,(c['id'],u,b.fen())
                    b.push(m)
            else:
                checks={'mate':b.is_checkmate(),'stalemate':b.is_stalemate(),'no_castle':chess.Move.from_uci('e1g1') not in b.legal_moves,'no_ep':not b.has_legal_en_passant()}
                assert checks[s['answer']],c['id']
